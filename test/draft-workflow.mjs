import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import puppeteer from 'puppeteer-core';
import {startServer} from '../dist/server.js';
import {historyStore} from '../dist/revisions.js';

const dir=fs.mkdtempSync(path.join(os.tmpdir(),'slidex-draft-workflow-'));
const file=path.join(dir,'original.slx'),newFile=path.join(dir,'saved-new.slx'),secondFile=path.join(dir,'saved-before-new.slx');
const original='<deck version="1" title="Original"><slide id="one"/></deck>';
fs.writeFileSync(file,original);
const preferencesFile=path.join(dir,'profile','preferences.json');
const server=await startServer(file,{port:0,preferencesFile});
const browser=await puppeteer.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox']});
const page=await browser.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
page.on('dialog',dialog=>void dialog.accept());
const history=historyStore(path.join(dir,'profile','history'));
const api=async endpoint=>page.evaluate(async endpoint=>(await(await fetch(endpoint)).json()),endpoint);
try{
  await page.goto(`http://127.0.0.1:${server.port}`);
  await page.waitForSelector('[aria-label="演示文稿标题"]');
  await page.locator('[aria-label="演示文稿标题"]').fill('Draft title');
  await page.waitForFunction(async()=>!!(await(await fetch('/api/revisions')).json()).revisions.find(r=>r.draft&&r.xml.includes('Draft title')));
  await new Promise(resolve=>setTimeout(resolve,2200));
  assert.equal(fs.readFileSync(file,'utf8'),original,'background draft must not overwrite the original');
  assert.match(history.read(file).draft.xml,/Draft title/);
  const exportSnapshot=async()=>page.evaluate(async()=>{
    const response=await fetch('/api/export',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({format:'html',xml:window.__slxGetXml()})});
    return response.json();
  });
  const existingExport=await exportSnapshot();
  assert.equal(existingExport.ok,true,existingExport.error);
  assert.match(fs.readFileSync(existingExport.files[0],'utf8'),/<title>Draft title<\/title>/);
  assert.equal(fs.readFileSync(file,'utf8'),original,'export must not save the source document');
  await page.reload();
  await page.waitForSelector('[role="dialog"] button');
  assert.match(await page.$eval('[role="dialog"]',el=>el.textContent),/发现未保存的恢复草稿/);
  await page.locator('[role="dialog"] button::-p-text(恢复草稿)').click();
  await page.waitForSelector('[role="dialog"]',{hidden:true});
  assert.equal(await page.$eval('[aria-label="演示文稿标题"]',el=>el.value),'Draft title');
  await page.locator('button::-p-text(文件)').click();
  await page.locator('[role="menuitem"]::-p-text(新建…)').click();
  await page.locator('[role="dialog"] button::-p-text(丢弃)').click();
  await page.waitForFunction(async()=>!(await(await fetch('/api/deck')).json()).path);
  assert.equal(fs.readFileSync(file,'utf8'),original);
  assert.equal(history.read(file).draft,undefined);
  assert.equal(await api('/api/deck').then(data=>data.path),'');
  assert.equal(fs.existsSync(newFile),false);
  await page.locator('[aria-label="演示文稿标题"]').fill('New in memory');
  await page.waitForFunction(async()=>!!(await(await fetch('/api/revisions')).json()).revisions.find(r=>r.draft&&r.xml.includes('New in memory')));
  assert.equal(fs.existsSync(newFile),false);
  const untitledExport=await exportSnapshot();
  assert.equal(untitledExport.ok,true,untitledExport.error);
  assert.match(fs.readFileSync(untitledExport.files[0],'utf8'),/<title>New in memory<\/title>/);
  assert.equal(fs.existsSync(newFile),false);
  await page.locator('button::-p-text(文件)').click();
  await page.locator('[role="menuitem"]::-p-text(保存)').click();
  await page.waitForSelector('[role="dialog"] [aria-label="文件路径"]');
  await page.locator('[role="dialog"] [aria-label="文件路径"]').fill(newFile);
  await page.locator('[role="dialog"] button::-p-text(保存)').click();
  await page.waitForFunction(async()=>!!(await(await fetch('/api/deck')).json()).path.endsWith('saved-new.slx'));
  await page.waitForSelector('[role="dialog"]',{hidden:true});
  assert.match(fs.readFileSync(newFile,'utf8'),/New in memory/);
  assert.equal(history.read('').draft,undefined);
  await page.locator('button::-p-text(文件)').click();
  await page.locator('[role="menuitem"]::-p-text(新建…)').click();
  await page.waitForFunction(async()=>!(await(await fetch('/api/deck')).json()).path);
  await page.waitForFunction(()=>document.querySelector('[aria-label="演示文稿标题"]')?.value==='未命名演示');
  await page.locator('[aria-label="演示文稿标题"]').fill('Next');
  await page.waitForFunction(()=>document.querySelector('[aria-label="演示文稿标题"]')?.value==='Next');
  await page.locator('button::-p-text(文件)').click();
  await page.evaluate(()=>document.querySelector('[role="menuitem"]')?.click());
  await page.waitForSelector('[role="dialog"] button::-p-text(丢弃)');
  await page.locator('[role="dialog"] button::-p-text(保存)').click();
  await page.waitForSelector('[role="dialog"] [aria-label="文件路径"]');
  await page.locator('[role="dialog"] [aria-label="文件路径"]').fill(secondFile);
  await page.locator('[role="dialog"] button::-p-text(保存)').click();
  await page.waitForFunction(async()=>!(await(await fetch('/api/deck')).json()).path&&document.querySelector('[aria-label="演示文稿标题"]')?.value==='未命名演示');
  assert.match(fs.readFileSync(secondFile,'utf8'),/title="Next"/);
  assert.deepEqual(errors,[]);
  console.log('PASS draft only saves on command, restores after reload, and new document stays in memory');
}finally{await browser.close();server.close();}
const untitled=await startServer('',{port:0,preferencesFile:path.join(dir,'fresh-profile','preferences.json')});
try{
  const base=`http://127.0.0.1:${untitled.port}`;
  const deck=await(await fetch(base+'/api/deck')).json();
  assert.equal(deck.path,'');
  assert.equal(deck.mtimeMs,0);
  assert.match(deck.xml,/未命名演示/);
  assert.equal(fs.existsSync(path.join(dir,'fresh-profile','untitled.slx')),false);
  const next=await fetch(base+'/api/new-document',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({expectedPath:'',expectedVersion:deck.version})});
  assert.equal(next.status,200);
  const stale=await fetch(base+'/api/draft',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({path:'',expectedVersion:deck.version,xml:deck.xml.replace('未命名演示','Old draft')})});
  assert.equal(stale.status,409,'a previous untitled document must not write into the new one');
  assert.equal((await(await fetch(base+'/api/revisions')).json()).revisions.length,0);
}finally{untitled.close();}
