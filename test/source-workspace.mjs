import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import puppeteer from 'puppeteer-core';
import { startServer } from '../dist/server.js';
import { parseXML } from '../dist/parser.js';

assert.ok(parseXML('<deck><').errors.some(error=>error.code==='E_XML'));

const dir=fs.mkdtempSync(path.join(os.tmpdir(),'slidex-source-'));
const file=path.join(dir,'source.slx');
fs.writeFileSync(file,'<deck version="1" width="640" height="360"><slide id="first"><text id="label" x="30" y="40" w="200" h="60">Before</text></slide></deck>');
const server=await startServer(file,{port:0,preferencesFile:path.join(dir,'preferences.json')});
const browser=await puppeteer.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox']});
const page=await browser.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.setViewport({width:1400,height:900});
const base=`http://127.0.0.1:${server.port}`;
try{
  console.log('source test: load canvas');
  await page.goto(base);await page.waitForSelector('#canvasHost [data-id="label"]');
  await page.locator('.ribbon-tab::-p-text(工具)').click();
  await page.click('.ribbon-panel [aria-label="DSL 源码与检查…"]');
  console.log('source test: open Monaco');
  await page.waitForSelector('.source-workspace .monaco-editor',{timeout:20000});
  assert.equal(new URL(page.url()).pathname,'/source');
  assert.equal(await page.$('[role="dialog"]'),null);
  assert.match(await page.$eval('.source-outline',el=>el.textContent),/first/);
  console.log('source test: edit invalid XML');
  await page.click('.source-monaco .view-lines');
  console.log('source test: clicked editor');
  await page.keyboard.down('Control');await page.keyboard.press('a');await page.keyboard.up('Control');
  console.log('source test: selected all');
  await page.keyboard.type('<deck><broken>');
  console.log('source test: typed invalid XML');
  await page.waitForSelector('.source-diagnostic-list button',{timeout:10000});
  console.log('source test: validate and exit');
  await page.locator('button::-p-text(验证并应用)').click();
  assert.equal(new URL(page.url()).pathname,'/source');
  await page.locator('button[aria-label="返回画布"]').click();
  await page.waitForSelector('[role="dialog"][data-state="open"]');
  await page.locator('[role="dialog"][data-state="open"] button::-p-text(继续编辑)').click();
  assert.equal(new URL(page.url()).pathname,'/source');
  await page.waitForSelector('[role="dialog"]',{hidden:true});
  await page.locator('button[aria-label="返回画布"]').click();
  await page.locator('[role="dialog"][data-state="open"] button::-p-text(丢弃)').click();
  await page.waitForSelector('#canvasHost [data-id="label"]');
  assert.equal(new URL(page.url()).pathname,'/');
  console.log('source test: direct route');
  await page.goto(base+'/source');await page.waitForSelector('.source-workspace .monaco-editor',{timeout:20000});
  assert.match(await page.$eval('.source-outline',el=>el.textContent),/first/);
  await page.locator('button[aria-label="返回画布"]').click();
  await page.waitForSelector('#canvasHost [data-id="label"]');
  await page.waitForSelector('[role="dialog"]',{hidden:true});
  await page.locator('.ribbon-tab::-p-text(工具)').click();
  await page.click('.ribbon-panel [aria-label="DSL 源码与检查…"]');
  await page.waitForSelector('.source-workspace .monaco-editor');
  await page.waitForSelector('.source-monaco textarea.inputarea');
  await page.waitForFunction(()=>document.activeElement?.classList.contains('inputarea'));
  await page.keyboard.down('Control');await page.keyboard.press('a');await page.keyboard.up('Control');
  await page.keyboard.type('<deck version="1" width="640" height="360"><slide id="updated"><text id="label" x="30" y="40" w="200" h="60">After</text></slide></deck>');
  await page.waitForFunction(()=>document.querySelector('.source-outline')?.textContent.includes('updated'));
  await page.locator('button::-p-text(验证并应用)').click();
  await page.waitForSelector('#canvasHost [data-id="label"]');
  assert.equal(new URL(page.url()).pathname,'/');
  assert.match(await page.evaluate(()=>window.__slxGetXml()),/After/);
  await page.locator('.ribbon-tab::-p-text(工具)').click();
  await page.click('.ribbon-panel [aria-label="DSL 源码与检查…"]');
  await page.waitForFunction(()=>document.activeElement?.classList.contains('inputarea'));
  await page.locator('.source-header-actions button::-p-text(格式化)').click();
  await page.locator('.source-header-actions button::-p-text(保存)').click();
  await page.waitForFunction(()=>document.querySelector('.source-statusbar')?.textContent.includes('所有更改已保存'));
  assert.match(fs.readFileSync(file,'utf8'),/After/);
  await page.click('button[aria-label="返回画布"]');
  await page.waitForSelector('#canvasHost [data-id="label"]');
  assert.deepEqual(errors,[]);
  console.log('PASS Monaco source workspace, diagnostics, protected exit, direct route, save');
}finally{await browser.close();server.close();}
