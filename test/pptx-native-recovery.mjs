import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {loadProject} from '../dist/project.js';
import {parseSlideX} from '../dist/ir.js';
import {planSlide} from '../dist/export/pptx-native.js';
import {exportDeck} from '../dist/export/export.js';
import {unzipIndependent} from './pptx-integrity.mjs';

const source=path.resolve('test/fixtures/pptx-native-recovery.slx');
const deck=loadProject(source).deck;
for(const slide of deck.slides)assert.ok(planSlide(deck,slide).items.every(item=>item.kind!=='crop'));
const unsupported=parseSlideX('<deck version="1"><slide><shape id="overlap" name="rect" x="10" y="10" w="90" h="60" fill="#336699" stroke="#000000" opacity="0.5"/><text id="shadow" x="10" y="80" w="120" h="30" opacity="0.5" shadow="2 1 1 #000000">Shadow</text></slide></deck>').deck;
assert.deepEqual(planSlide(unsupported,unsupported.slides[0]).items.map(item=>item.reason),['opacity','opacity']);
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'slidex-native-recovery-'));
const result=await exportDeck(source,{format:'pptx',editable:true,directory});
assert.deepEqual(result.report.summary,{native:6,rasterized:0,unsupported:0});
const parts=await unzipIndependent(fs.readFileSync(result.files[0]));
const opacity=parts.get('ppt/slides/slide1.xml').toString();
assert.match(opacity,/name="text transparent-text"/);
assert.match(opacity,/name="rect transparent-shape"/);
assert.match(opacity,/<a:alpha val="50000"\/>/);
assert.match(opacity,/<a:alpha val="45000"\/>/);
assert.match(opacity,/tIns="-60960"/);
assert.doesNotMatch(opacity,/render transparent-/);
const line=parts.get('ppt/slides/slide2.xml').toString();
assert.match(line,/name="line loop"/);
assert.match(line,/<a:custGeom>/);
assert.equal((line.match(/<a:lnTo>/g)||[]).length,3);
assert.match(line,/<a:tailEnd type="stealth"/);
assert.doesNotMatch(line,/render loop/);
const chart=parts.get('ppt/charts/chart1.xml').toString();
assert.match(chart,/<c:dLbls>/);
assert.match(chart,/<c:showVal val="1"\/>/);
assert.match(chart,/formatCode="0.0"/);
assert.match(chart,/<c:max val="60"\/>/);
assert.match(chart,/<c:min val="0"\/>/);
const table=parts.get('ppt/slides/slide4.xml').toString();
const rowHeights=[...table.matchAll(/<a:tr h="(\d+)"/g)].map(match=>Number(match[1]));
assert.equal(rowHeights.length,3);
assert.ok(rowHeights[1]>rowHeights[0] && rowHeights[1]>rowHeights[2],`browser-measured row heights: ${rowHeights}`);
assert.ok(Math.abs(rowHeights.reduce((sum,height)=>sum+height,0)-180*12700)<12700);
console.log('PASS editable opacity, multi-point line, labeled chart, and measured table rows:',directory);
